def main():
    json_path = DATA / "pokemon.json"
    if not json_path.exists():
        print("data/pokemon.json não encontrado.")
        return

    pokemons = json.loads(json_path.read_text(encoding="utf-8"))
    print(f"• Traduzindo {len(pokemons)} Pokémon para Português do Brasil...")

    for p in pokemons:
        pid = p["id"]

        # Traduz espécie e descrição
        if pid in DESCRIPTIONS_PTBR:
            genus_pt, desc_pt = DESCRIPTIONS_PTBR[pid]
            p["genus"] = genus_pt
            p["description"] = desc_pt
            p["description_lang"] = "pt-br"

        # Traduz habilidades
        new_abilities = []
        for ab in p.get("abilities", []):
            orig_name = ab["name"]
            if orig_name in ABILITIES_PTBR:
                name_pt, desc_pt = ABILITIES_PTBR[orig_name]
                new_abilities.append({
                    "name": name_pt,
                    "hidden": ab.get("hidden", False),
                    "description": desc_pt,
                })
            else:
                new_abilities.append(ab)
        p["abilities"] = new_abilities

    json_path.write_text(json.dumps(pokemons, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"✔ Sucesso! Todos os {len(pokemons)} Pokémon foram atualizados em PT-BR.")


if __name__ == "__main__":
    main()

